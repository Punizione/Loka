"""Build an isolated L4D2 compile search path for exported include bundles."""
from pathlib import Path

from .vmodel import game_search_roots

_MARKER = "// Generated by Loka: compile output and included dependencies stay here."


def apply_nekomdl_max_bones(qc_path, compiler_path):
    """Silently opt generated viewmodel QCs into Neko's extended bone limit."""
    compiler = Path(compiler_path)
    if compiler.name.lower() != 'nekomdl.exe' or not compiler.is_file():
        return
    from .weapon_qc import parse_qc, _tokens, _resource_tokens, _patch

    qc = Path(qc_path)
    with qc.open(encoding='utf-8-sig', newline='') as handle:
        text = handle.read()
    commands = parse_qc(text)
    model = next((c.name.replace('\\', '/').lower() for c in commands if c.kind == 'modelname'), '')
    if model.startswith('models/'):
        model = model[7:]
    if not model.startswith(('v_models/', 'weapons/melee/v_', 'weapons/arms/v_')):
        return

    # Merge names, not per-file counts: each animation normally repeats the
    # mesh's entire skeleton. Read only nodes, never the large frame payloads.
    bones = {c.name.casefold() for c in commands if c.kind == 'definebone'}
    resources = dict.fromkeys(t.value.replace('\\', '/') for t in _resource_tokens(text)
                             if t.value.lower().endswith('.smd'))
    for relative in resources:
        if len(bones) >= 256:
            return
        active = False
        with (qc.parent/relative).open(encoding='utf-8-sig') as handle:
            for line in handle:
                if line.strip() == 'nodes':
                    active = True
                    continue
                if active and line.strip() == 'end':
                    break
                if active:
                    values = _tokens(line)
                    if len(values) == 3:
                        bones.add(values[1].value.casefold())
    if not 128 < len(bones) < 256:
        return

    tokens = _tokens(text)
    changes = []
    depth = 0
    first_is_maxbones = bool(tokens and tokens[0].value.lower() == '$maxbones' and not tokens[0].quoted)
    for index, token in enumerate(tokens):
        if token.quoted:
            continue
        if token.value == '{':
            depth += 1
        elif token.value == '}':
            depth -= 1
        elif depth == 0 and token.value.lower() == '$maxbones':
            end = token.end
            if index + 1 < len(tokens):
                value = tokens[index + 1]
                if value.quoted or (not value.value.startswith('$') and value.value not in ('{', '}')):
                    end = value.end
            changes.append((token.start, end, '$MaxBones 256' if index == 0 else ''))
    updated = _patch(text, changes)
    if not first_is_maxbones:
        updated = '$MaxBones 256'+ ('\r\n' if '\r\n' in text else '\n') + updated
    if updated != text:
        with qc.open('w', encoding='utf-8', newline='') as handle:
            handle.write(updated)


def is_compile_bundle(path: str) -> bool:
    """Generated dependency packages must not become recursive batch inputs."""
    try:
        with (Path(path) / "gameinfo.txt").open(encoding="utf-8-sig") as handle:
            return handle.read(len(_MARKER)) == _MARKER
    except (OSError, UnicodeError):
        return False


def prepare_compile_game(output_path: str, game_dir: str = "", dependency_path: str = "", *, extra_dependency_paths=()) -> str:
    output = Path(output_path).resolve()
    output.mkdir(parents=True, exist_ok=True)
    marker = _MARKER
    gameinfo = output / "gameinfo.txt"
    if gameinfo.exists() and not gameinfo.read_text(encoding="utf-8-sig").startswith(marker):
        raise FileExistsError(f"输出目录已有游戏配置，不能覆盖: {gameinfo}；请选择独立输出目录")
    search_paths = ['Game "|gameinfo_path|."']
    roots = (([Path(dependency_path).resolve()] if dependency_path else [])
             + [Path(p).resolve() for p in extra_dependency_paths] + game_search_roots(game_dir))
    for path in dict.fromkeys(roots):
        if path.is_dir() and path != output:
            search_paths.append(f'Game "{path.as_posix()}"')
    text = (marker + '\n'
            '"GameInfo"\n{\n game "Loka compile"\n FileSystem\n {\n'
            '  SteamAppId 550\n  SearchPaths\n  {\n   ' + '\n   '.join(search_paths) + '\n  }\n }\n}\n')
    gameinfo.write_text(text, encoding="utf-8")
    return str(output)
