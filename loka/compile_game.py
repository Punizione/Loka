"""Build an isolated L4D2 compile search path for exported include bundles."""
from pathlib import Path

from .vmodel import game_search_roots

_MARKER = "// Generated by Loka: compile output and included dependencies stay here."


def is_compile_bundle(path: str) -> bool:
    """Generated dependency packages must not become recursive batch inputs."""
    try:
        with (Path(path) / "gameinfo.txt").open(encoding="utf-8-sig") as handle:
            return handle.read(len(_MARKER)) == _MARKER
    except (OSError, UnicodeError):
        return False


def prepare_compile_game(output_path: str, game_dir: str = "", dependency_path: str = "", *, extra_dependency_paths=()) -> str:
    output = Path(output_path).resolve()
    output.mkdir(parents=True, exist_ok=True)
    marker = _MARKER
    gameinfo = output / "gameinfo.txt"
    if gameinfo.exists() and not gameinfo.read_text(encoding="utf-8-sig").startswith(marker):
        raise FileExistsError(f"输出目录已有游戏配置，不能覆盖: {gameinfo}；请选择独立输出目录")
    search_paths = ['Game "|gameinfo_path|."']
    roots = (([Path(dependency_path).resolve()] if dependency_path else [])
             + [Path(p).resolve() for p in extra_dependency_paths] + game_search_roots(game_dir))
    for path in dict.fromkeys(roots):
        if path.is_dir() and path != output:
            search_paths.append(f'Game "{path.as_posix()}"')
    text = (marker + '\n'
            '"GameInfo"\n{\n game "Loka compile"\n FileSystem\n {\n'
            '  SteamAppId 550\n  SearchPaths\n  {\n   ' + '\n   '.join(search_paths) + '\n  }\n }\n}\n')
    gameinfo.write_text(text, encoding="utf-8")
    return str(output)
