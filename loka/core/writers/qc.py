class _Settings:
    """Reads the parser's option flags from either the VB property names or the port's.

    ``loka.decompiler.DecompileOptions`` exposes snake_case field names; the
    VB original uses ``TheApp.Settings.Decompile...IsChecked``.  Both spellings are
    accepted so the writer can be driven from either side without edits.
    """

    def __init__(self, options: Any) -> None:
        self._options = options

    @property
    def options(self) -> Any:
        return self._options

    def _flag(self, *names: str, default: bool = False) -> bool:
        for name in names:
            if self._options is None:
                break
            value = getattr(self._options, name, _UNKNOWN)
            if value is not _UNKNOWN:
                return bool(value)
        return default

    def _value(self, *names: str, default: Any = None) -> Any:
        """Same lookup as :meth:`_flag` for non-boolean options."""
        for name in names:
            if self._options is None:
                break
            value = getattr(self._options, name, _UNKNOWN)
            if value is not _UNKNOWN:
                return value
        return default

