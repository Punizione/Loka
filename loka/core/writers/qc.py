            for a_skin_family in skin_families:
                line = _TAB + "{ "
                for texture_file_name_index in range(len(a_skin_family)):
                    a_texture_file_name = a_skin_family[texture_file_name_index]
                    length = texture_file_name_max_lengths[texture_file_name_index]
                    text = '"' + a_texture_file_name + '"'
                    # LSet: left-justify, pad right, truncate when already longer.
                    line += text.ljust(length + 3)[: length + 3]
