class QcFile49:
    """Implement ``SourceQcFile49``.

    ``write_line`` is the parser's ``StreamWriter.WriteLine``; the constructor also
    accepts any object exposing ``write_line`` (e.g. the SMD writer's text writer).
    """

    def __init__(
        self,
        write_line: Callable[[str], None],
        mdl_file_data: SourceMdlFileData49,
        vtx_file_data: Any = None,
        phy_file_data: Any = None,
        model_name: str = "",
        *,
        registry: Any = None,
        options: Any = None,
        output_path: Optional[str] = None,
        output_file_name_without_extension: Optional[str] = None,
    ) -> None:
        if not callable(write_line):
            write_line = write_line.write_line
        self.write_line = write_line

        self.theMdlFileData = mdl_file_data
        self.theVtxFileData = vtx_file_data
        self.thePhyFileData = phy_file_data
        self.theModelName = model_name
        self.registry = registry
        self.theSettings = _Settings(options)

        # QCI grouping needs the output location; when it is not supplied the group
        # content is emitted inline instead (see ``write_group``).
        self.theOutputPath = output_path
        self.theOutputFileNameWithoutExtension = output_file_name_without_extension

        # Per-call state
        self.theBodyPartForFlexWriting: Any = None
        self.theFlexControllerNames: list[str] = []
        self._qc_lines: list[str] = []
        #: ``write_text_lines`` holds the current key here until its value arrives.
        self._pending_record: Optional[str] = None

    # -- low level ---------------------------------------------------------
    def write(self, text: str) -> None:
        """``StreamWriter.Write`` -- continues the current line (no terminator)."""
        if self._qc_lines:
            self._qc_lines[-1] += text
        else:
            self._qc_lines.append(text)

    def write_raw(self, text: str) -> None:
        self.write(text)

    # -- helpers -----------------------------------------------------------
    @property
    def _target(self) -> Callable[[str], None]:
        return self._qc_lines.append

    def _emit(self, text: str = "") -> None:
        self._qc_lines.append(text)

    def _flush(self) -> None:
        lines = self._qc_lines
        self._qc_lines = []
        for line in lines:
            self.write_line(line)

    @property
    def _mixed_case(self) -> bool:
        return self.theSettings.decompile_qc_use_mixed_case_for_keywords_is_checked

    def _command(self, lowercase: str, camel_case: str) -> str:
        return camel_case if self._mixed_case else lowercase

    def _bones(self) -> list:
        return self.theMdlFileData.theBones or []

    # ------------------------------------------------------------------
    # Top level
    # ------------------------------------------------------------------
    def write_animation_library(self) -> None:
        """Export a mesh-free included v_model library, preserving animation semantics."""
        try:
            self.write_header_comment()
            self.write_model_name_command()
            self.write_up_axis_command()
            self.write_attachment_command()
            self.write_controller_command()
            self.write_group_bone()
            self.set_up_corrective_subtract_animation_blocks()
            self.write_group_animation()
            self.write_key_values(self.theMdlFileData.theKeyValuesText,
                                  self._command("$keyvalues", "$KeyValues"))
        finally:
            self._flush()

    def write_all(self) -> None:
        """Implement ``SourceModel49.WriteQcFile``'s call order (§2 of the spec).

        The VB original wraps the whole sequence in ``Try ... Catch`` with an empty
        handler, so any exception silently truncates the file.  That behaviour is
        reproduced deliberately -- see ``_swallow``.
        """
        try:
            self.write_header_comment()
            self.write_model_name_command()

            self.write_up_axis_command()
            self.write_static_prop_command()
            self.write_constant_directional_light_command()

            self.write_body_group_command()
            self.write_body_group_preset_command()
            self.write_group("lod", self.write_group_lod, False, False)

            self.write_surface_prop_command()
            self.write_joint_surface_prop_command()
            self.write_contents_command()
            self.write_joint_contents_command()
            self.write_illum_position_command()

            self.write_eye_position_command()
            self.write_max_eye_deflection_command()
            self.write_no_forced_fade_command()
            self.write_force_phoneme_crossfade_command()

            self.write_ambient_boost_command()
            self.write_opaque_command()
            self.write_obsolete_command()
            self.write_cast_texture_shadows_command()
            self.write_do_not_cast_shadows_command()
            self.write_cd_materials_command()
            self.write_texture_group_command()
            if self.theSettings.decompile_debug_info_files_is_checked:
                self.write_texture_file_name_comments()

            self.write_attachment_command()

            self.write_group("box", self.write_group_box, True, False)

            self.write_controller_command()
            self.write_screen_align_command()

            self.write_group("bone", self.write_group_bone, False, False)

            self.set_up_corrective_subtract_animation_blocks()
            self.write_group("animation", self.write_group_animation, False, False)

            self.write_group("collision", self.write_group_collision, False, False)

            self.write_key_values(
                self.theMdlFileData.theKeyValuesText,
                self._command("$keyvalues", "$KeyValues"),
            )

            # NOTE: no trailing blank line is emitted.  `SmdTextWriter` terminates every
            # line with CRLF, so the file already ends with exactly one newline after the
            # last command -- which is what the golden files show.
        except MemoryError:
            raise
        except Exception:
            # Mirrors the empty ``Catch ex As Exception`` in ``WriteQcFile``: the
            # file is truncated at the failing command.
            pass
        finally:
            self._flush()

    # ------------------------------------------------------------------
    # QCI grouping
    # ------------------------------------------------------------------
    def write_group(
        self,
        qci_group_name: str,
        write_group_action: Callable[[], None],
        include_line_is_commented: bool,
        include_line_is_indented: bool,
    ) -> None:
        """Implement ``SourceQcFile49.WriteGroup`` (lines 47-111)."""
        if not self.theSettings.decompile_group_into_qci_files_is_checked:
            write_group_action()
            return

        qci_file_name = (
            (self.theOutputFileNameWithoutExtension or self.theModelName)
            + "_"
            + qci_group_name
            + ".qci"
        )
        qci_path_file_name = (
            os.path.join(self.theOutputPath, qci_file_name)
            if self.theOutputPath
            else qci_file_name
        )

        saved_lines = self._qc_lines
        self._qc_lines = []
        try:
            write_group_action()
        finally:
            group_lines = self._qc_lines
            self._qc_lines = saved_lines

        try:
            os.makedirs(os.path.dirname(qci_path_file_name) or ".", exist_ok=True)
            with open(qci_path_file_name, "w", encoding="utf-8", newline="") as handle:
                for line in group_lines:
                    handle.write(line)
                    handle.write("\r\n")
        except OSError:
            # Cannot route the group to a file: fall back to emitting it inline.
            for line in group_lines:
                self._emit(line)
            return

        if group_lines:
            # Mirrors ``FileInfo.Length > 0``: an empty group gets no include line.

            self._emit()
