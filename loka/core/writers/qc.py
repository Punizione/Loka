    def write_lod_command(self) -> None:
        """Implement ``WriteLodCommand`` (lines 1155-1289).

        Side effect (load bearing): writes ``theSmdFileNames[0]`` and
        ``theSmdFileNames[lodIndex]`` back into every body model, which
        ``SourceModel49.WriteMeshSmdFiles`` reads afterwards.
        """
        if self.theVtxFileData is None or self.theMdlFileData.theBodyParts is None:
            return

        vtx_body_parts = _get(self.theVtxFileData, "theVtxBodyParts", None)
        if vtx_body_parts is None:
            return
        if not vtx_body_parts or _get(vtx_body_parts[0], "theVtxModels", None) is None:
            return
        if (
            not vtx_body_parts[0].theVtxModels
            or _get(vtx_body_parts[0].theVtxModels[0], "theVtxModelLods", None) is None
        ):
            return

        # SortedList(Of Single, ...) -- ascending key order, shadow LOD (-1) last.
        lod_list: dict[float, list] = {}
        lod_list_of_facial_flags: dict[float, bool] = {}

        body_parts = self.theMdlFileData.theBodyParts
        for body_part_index in range(len(vtx_body_parts)):
            a_body_part = vtx_body_parts[body_part_index]
            vtx_models = _get(a_body_part, "theVtxModels", None)
            if vtx_models is None:
                continue

            for model_index in range(len(vtx_models)):
                a_vtx_model = vtx_models[model_index]
                vtx_model_lods = _get(a_vtx_model, "theVtxModelLods", None)
                if vtx_model_lods is None:
                    continue

                if body_part_index >= len(body_parts):
                    continue
                part_models = _get(body_parts[body_part_index], "theModels", None) or []
                if model_index >= len(part_models):
                    continue
                a_body_model = part_models[model_index]

                if self._is_blank_model(a_body_model, a_vtx_model):
                    continue

                lod_count = _get(self.theVtxFileData, "lodCount", 0)
                for lod_index in range(1, lod_count):
                    if lod_index >= len(vtx_model_lods):
                        break

                    switch_point = _get(vtx_model_lods[lod_index], "switchPoint", 0.0)
                    if switch_point not in lod_list:
                        lod_list[switch_point] = []
                        lod_list_of_facial_flags[switch_point] = _get(
                            vtx_model_lods[lod_index], "theVtxModelLodUsesFacial", False
                        )

                    smd_names = _get(a_body_model, "theSmdFileNames", None)
                    if smd_names is None:
                        continue
                    body_model_name = _get(a_body_model, "name", "")
                    smd_names[0] = self._create_body_group_smd_file_name(
                        smd_names[0], body_part_index, model_index, 0, body_model_name
                    )
                    smd_names[lod_index] = self._create_body_group_smd_file_name(
                        smd_names[lod_index],
                        body_part_index,
                        model_index,
                        lod_index,
                        body_model_name,
                    )
                    lod_list[switch_point].append(
                        (smd_names[0], smd_names[lod_index])
                    )

        self._emit()

        shadow_lod_list = None
        lod_index = 0
        for switch_point in sorted(lod_list.keys()):
            if switch_point == -1:
                shadow_lod_list = lod_list[switch_point]
                continue
            lod_index += 1

            self._emit(self._command("$lod ", "$LOD ") + fmt_f6(switch_point))
            self._emit("{")
            self.write_lod_options(
                lod_index, lod_list_of_facial_flags[switch_point], lod_list[switch_point]
            )
            self._emit("}")

        lod_index = len(lod_list) - 1
        if shadow_lod_list is not None:
            self._emit(self._command("$shadowlod", "$ShadowLOD"))
            self._emit("{")
            self.write_lod_options(lod_index, False, shadow_lod_list)
            self._emit("}")

    def write_lod_options(
        self, lod_index: int, lod_uses_facial: bool, a_lod_qc_info_list: list
    ) -> None:
        """Implement ``WriteLodOptions`` (lines 1291-1384)."""
        for reference_file_name, lod_file_name in a_lod_qc_info_list:
            if lod_file_name == "":
                line = _TAB + "removemodel " + '"' + reference_file_name + '"'
            else:
                line = (
                    _TAB
                    + "replacemodel "
                    + '"'
                    + reference_file_name
                    + '" "'
                    + lod_file_name
                    + '"'
                )
            self._emit(line)

        try:
            material_replacement_lists = _get(
                self.theVtxFileData, "theVtxMaterialReplacementLists", None
            )
            material_replacement_list = material_replacement_lists[lod_index]
            replacements = _get(
                material_replacement_list, "theVtxMaterialReplacements", None
            )
            if replacements is not None:
                for material_replacement in replacements:
                    line = _TAB
                    line += "replacematerial "
                    line += '"'
                    line += self._modified_texture_file_name(
                        _get(material_replacement, "materialIndex", 0)
                    )
                    line += '" "'
                    line += _get(material_replacement, "theName", "")
                    line += '"'
                    self._emit(line)
        except MemoryError:
            raise
        except Exception:
            pass

        lod_flag_by_index = {
            1: BONE_USED_BY_VERTEX_LOD1,
            2: BONE_USED_BY_VERTEX_LOD2,
            3: BONE_USED_BY_VERTEX_LOD3,
            4: BONE_USED_BY_VERTEX_LOD4,
            5: BONE_USED_BY_VERTEX_LOD5,
            6: BONE_USED_BY_VERTEX_LOD6,
            7: BONE_USED_BY_VERTEX_LOD7,
        }
        for a_bone in self._bones():
            parent_index = _get(a_bone, "parentBoneIndex", -1)
            if parent_index < 0:
                continue
            flag = lod_flag_by_index.get(lod_index)
            if flag is not None and (_get(a_bone, "flags", 0) & flag) == 0:
                line = _TAB
                line += "replacebone "
                line += '"'
                line += _get(a_bone, "theName", "")
                line += '" "'
                bone_name = ""
                if 0 <= parent_index < len(self._bones()):
                    bone_name = _get(self._bones()[parent_index], "theName", "")
                line += bone_name
                line += '"'
                self._emit(line)

        self._emit(
            _TAB + self._command("facial", "Facial") if lod_uses_facial else _TAB + self._command("nofacial", "NoFacial")
        )

        if (self.theMdlFileData.flags & STUDIOHDR_FLAGS_USE_SHADOWLOD_MATERIALS) > 0:
            self._emit()
            self._emit(self._command("use_shadowlod_materials", "Use_ShadowLOD_Materials"))

