    def _create_animation_smd_relative_path_file_name(
        self, given: str, animation_name: str
    ) -> str:
        """Implement ``SourceFileNamesModule.CreateAnimationSmdRelativePathFileName``.

        Differences from :mod:`loka.core.naming`'s version: the VB original
        registers the **full relative path** (not just the basename) with
        ``GetUniqueSmdFileName``, only appends ``.smd`` when the extension is not
        already ``.smd``, and never prepends the model name to the animation name.

        The VB MDL reader leaves ``theSmdRelativePathFileName`` as ``""`` (only the
        QC writer fills it in), so a value that the reader *did* synthesise is
        ignored here -- see :meth:`_looks_like_parser_generated_animation_path`.
        """
        if given and not self._looks_like_parser_generated_animation_path(given, animation_name):
            return given

        animation_name = (animation_name or "").strip("\x00")
        for ch in _INVALID_FILE_NAME_CHARS:
            animation_name = animation_name.replace(ch, "")
        if not animation_name:
            animation_name = "anim"

        if animation_name.startswith("@"):
            name = animation_name[1:]
        else:
            name = animation_name

        # NOTE: the model name is only prepended when animations are kept out of the
        # subfolder -- the VB original does not add it otherwise.
        if not self.theSettings.decompile_bone_animation_place_in_subfolder_is_checked:
            name = self.theModelName + "_anim_" + animation_name

        relative_path = _get_animation_smd_relative_path(
            self.theModelName,
            self.theSettings.decompile_bone_animation_place_in_subfolder_is_checked,
        )
        relative_path_file_name = _path_combine(relative_path, name)
        relative_path_file_name = self._registry.get_unique_smd_file_name(
            relative_path_file_name
        )
        if _get_extension(relative_path_file_name) != ".smd":
            relative_path_file_name += ".smd"
        return relative_path_file_name

    def _looks_like_parser_generated_animation_path(
        self, given: str, animation_name: str
    ) -> bool:
        """Detect a name the MDL reader synthesised via ``core.naming``.

        The reader pre-fills ``theSmdRelativePathFileName`` with
        ``<model>_anims\\<model>_<animation>.smd`` (it prepends the model name), but
        the parser's own reader leaves the field empty and the QC writer builds
        ``<model>_anims\\<animation>.smd``.  Treating the reader's value as
        pre-supplied data would rename every animation SMD, so it is regenerated.
        """
        relative_path = _get_animation_smd_relative_path(
            self.theModelName,
            self.theSettings.decompile_bone_animation_place_in_subfolder_is_checked,
        )
        if _get_path(given) != relative_path:
            return False

        base = _get_file_name_without_extension(given)
        model_prefix = self.theModelName + "_"
        if not base.lower().startswith(model_prefix.lower()):
            return False

        base_without_prefix = base[len(model_prefix) :].lower()
        for candidate in (
            (animation_name or "").strip("\x00").lower(),
            (animation_name or "").strip("\x00").lstrip("@").lower(),
        ):
            if not candidate:
                continue
            if base_without_prefix == candidate or base_without_prefix.startswith(
                candidate + "_blend"
            ):
                return True
        return False

