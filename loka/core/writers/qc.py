_UNKNOWN = object()


def _get(obj: Any, name: str, default: Any = _UNKNOWN) -> Any:
    """``getattr`` that tolerates the parser sections that are still unported."""
    value = getattr(obj, name, _UNKNOWN)
    if value is _UNKNOWN:
        if default is _UNKNOWN:
            raise AttributeError(f"{type(obj).__name__}.{name} is not available")
        return default
    return value


def _first(obj: Any, *names: str, default: Any = None) -> Any:
    """Return the first attribute that exists (parser field names still drift)."""
    for name in names:
        value = getattr(obj, name, _UNKNOWN)
        if value is not _UNKNOWN:
            return value
    return default


def round_dotnet(value: float, digits: int) -> float:
    """Implement VB ``Math.Round(value, digits)`` -- banker's rounding on a double.

    .NET Framework's ``Math.Round(Double, Int32)`` is documented as
    "multiply by 10^digits, round half to even, divide by 10^digits".  Doing the
    arithmetic in :mod:`decimal` (which is exact for binary floats) reproduces that
    observable behaviour without the double-rounding artifacts of
    ``round(value, digits)``.
    """
    if value is None:
        return 0.0
    value = float(value)
    if math.isnan(value) or math.isinf(value):
        return value
    if digits <= 0:
        quantum = Decimal(1)
    else:
        quantum = Decimal(1).scaleb(-digits)
    with _localcontext():
        return float(Decimal(value).quantize(quantum, rounding=ROUND_HALF_EVEN))


def _localcontext():
    from decimal import localcontext

    return localcontext()


def _dotnet_round_trip(value: float, significant: int) -> str:
    """Shortest decimal that round-trips, else ``significant`` significant digits.

    .NET Framework's ``Double.ToString()`` ("G15") emits at most 15 significant
    digits and *drops the trailing ".0"*.  .NET Core 3.0+ instead emits the
    shortest round-tripping decimal; both agree whenever the shortest form needs
    no more than 15 significant digits, which is the case for every value the QC
    writer emits (they all originate as 32-bit floats or small round numbers).
    """
    text = repr(value)
    if "e" in text or "E" in text or "inf" in text or "nan" in text:
        text = format(value, f".{significant}g")
    if len(text.lstrip("-").replace(".", "").lstrip("0")) > significant:
        text = format(value, f".{significant}g")
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    if text in ("", "-", "-0"):
        text = "0"
    return text


def fmt_g15(value: float) -> str:
    """VB ``aDouble.ToString(TheApp.InternalNumberFormat)`` -- G15, no trailing ``.0``."""
    if value is None:
        return "0"
    value = float(value)
    if math.isnan(value):
        return "NaN"
    if math.isinf(value):
        return "Infinity" if value > 0 else "-Infinity"
    return _dotnet_round_trip(value, 15)


def cstr_double(value: float) -> str:
    """VB ``CStr(aDouble)`` -- culture-sensitive; en-US matches :func:`fmt_g15`."""
    return fmt_g15(value)


def fmt_f0(value: float) -> str:
    """VB ``value.ToString("0", nf)`` -- rounded to an integer, no decimal point."""
    if value is None:
        return "0"
    value = float(value)
    if math.isnan(value):
        return "NaN"
    if math.isinf(value):
        return "Infinity" if value > 0 else "-Infinity"
    rounded = _drop_negative_zero(round_dotnet(value, 0))
    return format(Decimal(rounded).quantize(Decimal(1), rounding=ROUND_HALF_UP), "f")


def fmt_f2(value: float) -> str:
    """VB ``value.ToString("0.##", nf)`` -- max 2 decimals, trailing zeros trimmed."""
    return _format_trimmed(value, 2)


def fmt_f6(value: float) -> str:
    """VB ``value.ToString("0.######", nf)`` -- max 6 decimals, trimmed."""
    return _format_trimmed(value, 6)


def _drop_negative_zero(rounded):
    if rounded == 0:
        return abs(rounded)
    return rounded


def _format_trimmed(value: float, decimals: int) -> str:
    if value is None:
        return "0"
    value = float(value)
    if math.isnan(value):
        return "NaN"
    if math.isinf(value):
        return "Infinity" if value > 0 else "-Infinity"
    quantum = Decimal(1).scaleb(-decimals)
    with _localcontext():
        rounded = _drop_negative_zero(
            Decimal(value).quantize(quantum, rounding=ROUND_HALF_UP)
        )
    text = format(rounded, "f")
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    return text if text not in ("", "-") else "0"


def _cint(value: float) -> int:
    """Implement VB ``CInt(value)`` -- banker's rounding to the nearest integer."""
    if value is None:
        return 0
    value = float(value)
    if math.isnan(value) or math.isinf(value):
        return 0
    return int(round_dotnet(value, 0))


def _clone_vector(vector: Any) -> SourceVector:
    if vector is None:
        return SourceVector()
    x = _first(vector, "x", default=0.0)
    y = _first(vector, "y", default=0.0)
    z = _first(vector, "z", default=0.0)
    return SourceVector(x or 0.0, y or 0.0, z or 0.0)


def convert_rotation_matrix_to_degrees(
    m0: float, m1: float, m2: float, m3: float, m4: float, m5: float, m8: float
) -> tuple[float, float, float]:
    """Implement ``MathModule.ConvertRotationMatrixToDegrees`` (lines 123-152).

    The VB parameters are ``Single``, so the inputs are reduced to 32-bit floats
    before use -- that matters for ``Math.Round(m2, 6)`` near a midpoint.  The
    outputs are ``Double`` and are *not* re-rounded here; the caller rounds to
    two decimals, exactly as the VB caller does.
    """
    import struct

    def single(value: float) -> float:
        return struct.unpack("<f", struct.pack("<f", float(value)))[0]

    m0, m1, m2, m3, m4, m5, m8 = (single(v) for v in (m0, m1, m2, m3, m4, m5, m8))

    if m2 < -1:
        m2 = -1.0
    elif m2 > 1:
        m2 = 1.0

    angle_y = -math.asin(round_dotnet(m2, 6))
    c = math.cos(angle_y)
    angle_y = radians_to_degrees(angle_y)

    if abs(c) > 0.005:
        translate_x = round_dotnet(m8, 6) / c
        translate_y = round_dotnet(-m5, 6) / c
        angle_x = radians_to_degrees(math.atan2(translate_y, translate_x))
        translate_x = round_dotnet(m0, 6) / c
        translate_y = round_dotnet(-m1, 6) / c
        angle_z = radians_to_degrees(math.atan2(translate_y, translate_x))
    else:
        angle_x = 0.0
        translate_x = round_dotnet(m4, 6)
        translate_y = round_dotnet(m3, 6)
        angle_z = radians_to_degrees(math.atan2(translate_y, translate_x))

    return angle_x, angle_y, angle_z


