    def write_key_values(
        self,
        key_values_text: str,
        command_or_option_text: str,
        blank_starting_line_is_written: bool = True,
        indent_count: int = 0,
    ) -> None:
        """Implement ``WriteKeyValues`` (lines 5009-5053)."""
        try:
            if key_values_text is None or len(key_values_text) <= 0:
                return

            if blank_starting_line_is_written:
                self._emit()

            indent_text = _TAB * indent_count
            self._emit(indent_text + command_or_option_text)

            text = key_values_text.lstrip()
            start_text = "mdlkeyvalue\n"
            start_text2 = '"mdlkeyvalue"'
            if text.startswith(start_text):
                text = text[len(start_text) :]
            elif text.startswith(start_text2):
                text = text[len(start_text2) :]
            text = text.lstrip()

            if text[:1] != "{":
                # NOTE: the appended terminator is a bare LF, not CRLF.
                text = "{" + text + "}" + "\n"

            self.write_text_lines(text, indent_count)
        except MemoryError:
            raise
        except Exception:
            pass

    def write_text_lines(self, text: str, indent_count: int) -> None:
        """Implement ``WriteTextLines`` (lines 5054-5181).

        The routine is character-driven: ``{``/``}`` are structural and are re-emitted
        on their own lines, the text before a ``{`` becomes that block's header line,
        and a key is terminated by the value that follows it.

        Deviations from a literal transcription of the VB source (both are required to
        reproduce the parser's golden ``.qc`` output byte-for-byte; see the module report
        for the evidence):

        * a key/value record is terminated with a line break, so every
          ``"key" "value"`` pair lands on its own line.  The VB source uses a plain
          ``Write`` after the key and a ``WriteLine`` for the value, which does not in
          itself separate the records -- because the writer is always positioned at
          the start of a line, the append would instead glue the key to the *previous*
          record's value line.
        * a ``{`` reached while a record's terminating newline is still pending
          (``i == startIndex``) does not also emit a header line for that whitespace.
        """
        indent_text = _TAB * indent_count

        start_index = 0
        line_quote_count = 0
        section_name = ""
        pending_line: Optional[str] = None

        def flush_pending() -> None:
            nonlocal pending_line
            if pending_line is not None:
                self._emit(pending_line)
                pending_line = None

        for i in range(len(text)):
            text_char = text[i]

            if text_char == "{":
                if i > start_index:
                    untrimmed_section_name = text[start_index:i]
                    section_name = untrimmed_section_name.strip()

                    if pending_line is not None:
                        # ``{`` closing a named section.  VB writes the section header
                        # as ``indentText + sectionName`` and then
                        # ``indentText + <raw whitespace before the brace>``, which is
                        # what puts the second run of tabs before the trailing space
                        # (golden: ``\t\t"defaults"\t\t ``).
                        self._emit(pending_line + indent_text + untrimmed_section_name)
                        pending_line = None
                    elif section_name in ("qc_path", "animset_version 2 qc_path"):
                        self._emit(
                            "// CSGO compiler adds the "
                            + section_name
                            + " keyvalue section automatically."
                        )
                        line = "//" + indent_text
                        line += untrimmed_section_name
                        self._emit(line)
                    else:
                        section_name = ""
                        line = indent_text
                        line += untrimmed_section_name
                        self._emit(line)
                else:
                    flush_pending()

                line = ("//" if section_name != "" else "") + indent_text
                line += "{"
                self._emit(line)

                indent_count += 1
                indent_text = _TAB * indent_count

                start_index = i + 1
                line_quote_count = 0

            elif text_char == "}":
                flush_pending()
                if i > start_index:
                    before_close_brace_text = text[start_index:i].strip()
                    if before_close_brace_text != "":
                        line = ("//" if section_name != "" else "") + indent_text
                        line += before_close_brace_text
                        self._emit(line)

                indent_count -= 1
                indent_text = _TAB * indent_count

                if section_name != "":
                    line = "//" + indent_text
                    section_name = ""
                else:
                    line = indent_text
                line += "}"
                self._emit(line)

                start_index = i + 1
                line_quote_count = 0

            elif text_char == '"':
                line_quote_count += 1
                if line_quote_count == 2:
                    if i > start_index:
                        line = ("//" if section_name != "" else "") + indent_text
                        line += text[start_index : i + 1].strip()
                        # ``StreamWriter.Write``: the key opens a new physical line
                        # that the value following it completes.
                        pending_line = line
                    start_index = i + 1
                elif line_quote_count == 4:
                    if i > start_index:
                        # ``WriteLine(" " + value)`` closes the record.
                        line = " "
                        line += text[start_index : i + 1].strip()
                    else:
                        line = ""
                    if pending_line is not None:
                        line = pending_line + line
                        pending_line = None
                        self._emit(line)
                    elif line != "":
                        self._emit(line)
                    start_index = i + 1
                    line_quote_count = 0

            elif text_char == "\n":
                pending = text[start_index:i].strip()
                if line_quote_count == 0 and pending != "":
                    line = ("//" if section_name != "" else "") + indent_text
                    line += pending
                    self._emit(line)
                start_index = i + 1
                line_quote_count = 0

