def _get_file_name(path_file_name: str) -> str:
    text = (path_file_name or "").replace("/", "\\")
    index = text.rfind("\\")
    return text[index + 1 :] if index >= 0 else text


def _get_path(path_file_name: str) -> str:
    """Implement ``FileManager.GetPath`` -- the directory part, no trailing separator."""
    text = (path_file_name or "").replace("/", "\\")
    index = text.rfind("\\")
    return text[:index] if index > 0 else ""


def _get_file_name_without_extension(path_file_name: str) -> str:
    name = _get_file_name(path_file_name)
    index = name.rfind(".")
    return name[:index] if index > 0 else name


def _get_extension(path_file_name: str) -> str:
    name = _get_file_name(path_file_name)
    index = name.rfind(".")
    return name[index:] if index >= 0 else ""


_INVALID_FILE_NAME_CHARS = set('<>:"/\\|?*') | {chr(c) for c in range(0, 32)}


def _file_path_has_invalid_chars(value: str) -> bool:
    return any(ch in _INVALID_FILE_NAME_CHARS for ch in value)


def _get_clean_file_name_without_extension(given_file_name: str) -> str:
    cleaned = given_file_name
    for ch in _INVALID_FILE_NAME_CHARS:
        cleaned = cleaned.replace(ch, "")
    index = cleaned.rfind(".")
    if index > 0:
        cleaned = cleaned[:index]
    return cleaned


def _path_combine(left: str, right: str) -> str:
    if left == "":
        return right
    if right == "":
        return left
    return left + "\\" + right


